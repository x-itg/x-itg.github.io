def main():
    dump = (ROOT / "_ai_dump.txt").read_text(encoding="utf-8").split("\n")
    files = {}
    ok = miss = 0
    misses = []
    for idx, raw in enumerate(dump, 1):
        if idx not in REPL or not raw.strip():
            continue
        fname, _lineno, payload = raw.split("|", 2)
        if "[[[" not in payload:
            continue
        before, rest = payload.split("[[[", 1)
        span, after = rest.split("]]]", 1)
        new = REPL[idx]
        if fname not in files:
            files[fname] = (ROOT / fname).read_text(encoding="utf-8")
        text = files[fname]
        search = before + span + after
        if text.count(search) >= 1:
            files[fname] = text.replace(search, before + new + after, 1)
            ok += 1
        else:
            miss += 1
            misses.append((idx, fname, span[:30]))
    for fname, text in files.items():
        (ROOT / fname).write_text(text, encoding="utf-8")
    print("成功替换：", ok, " 失败：", miss)
    for m in misses:
        print("  未匹配 #%s %s : %s" % m)


main()
